import SwiftUI

@main
struct ImgManagerApp: App {
  var body: some Scene {
    // WP13 P11 (IMGMGR-220): a PARAMETERIZED window group — the second half of design decision
    // D6, "the second shoot beside the first". `WindowGroup(for:)` is what makes a window
    // addressable by a value, so `openWindow(value:)` can ask iPadOS for another one and the
    // system can restore it later. Unconditional: the capability and the entry point are
    // independent facts, and the built product already carries
    // `UIApplicationSupportsMultipleScenes = true` (probed on merkur before this change, phase
    // ledger — generated by `INFOPLIST_KEY_UIApplicationSceneManifest_Generation: YES`, so
    // project.yml needs no `info: properties:` addition).
    //
    // Ordinary launch presents no value, so `value` is nil and `RootView` behaves exactly as it
    // did — the restored/opened case is the only one that carries a shoot.
    WindowGroup(for: ShootSceneValue.self) { $value in
      #if DEBUG
        if DebugStubLaunch.isActive {
          // Diff-gate round 2, item 9(a): a DEBUG-only, launch-argument-gated fixture
          // composition for retained screenshot evidence — never reachable without BOTH the
          // Debug build configuration AND this explicit launch argument, and stripped entirely
          // from a Release/TestFlight archive.
          RootView(transport: DebugStubTransport())
        } else {
          RootView(shoot: value)
        }
      #else
        RootView(shoot: value)
      #endif
    }
    .commands {
      AppCommands()
    }
  }
}
